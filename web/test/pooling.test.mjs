import assert from 'node:assert/strict';
import { MinHeap, priorityFlood, computeWaterDepth } from '../js/pooling-core.js';

console.log('--- Running pooling-core unit tests ---');

// Test 1: MinHeap Ordering
{
  const heap = new MinHeap(4);
  heap.push(10, 5.0);
  heap.push(20, 2.0);
  heap.push(30, 8.0);
  heap.push(40, 1.5);

  assert.equal(heap.pop(), 40, 'Min element should be 40 (key 1.5)');
  assert.equal(heap.pop(), 20, 'Next min element should be 20 (key 2.0)');
  assert.equal(heap.pop(), 10, 'Next min element should be 10 (key 5.0)');
  assert.equal(heap.pop(), 30, 'Next min element should be 30 (key 8.0)');
  assert.equal(heap.pop(), -1, 'Empty heap returns -1');
  console.log('✓ MinHeap ordering passed');
}

// Test 2: Priority-Flood on 7x7 Bowl with Known Spill Height
{
  /**
   * 7x7 Bowl Grid:
   * Edge cells = 10.0 m (Boundary outlets)
   * Outer ring = 10.0 m
   * Single low notch on boundary: cell (3, 6) = 7.0 m (spillway lip)
   * Interior:
   *   Row 1-5, Col 1-5: 8.0 m
   *   Centre 3x3 (Row 2-4, Col 2-4): 2.0 m
   *   Dead centre (3, 3): 1.0 m
   *
   * With the lowest outlet on the perimeter at 7.0 m, the bowl's spill point must be 7.0 m!
   */
  const rows = 7;
  const cols = 7;
  const H = new Float32Array(cols * rows);

  // Fill default 10.0m
  H.fill(10.0);

  // Set interior bowl:
  for (let r = 1; r <= 5; r++) {
    for (let c = 1; c <= 5; c++) {
      H[r * cols + c] = 8.0;
    }
  }

  // Inner deep pocket
  for (let r = 2; r <= 4; r++) {
    for (let c = 2; c <= 4; c++) {
      H[r * cols + c] = 2.0;
    }
  }
  H[3 * cols + 3] = 1.0; // Pit bottom

  // Create spill notch at East boundary: (row 3, col 6) = 7.0 m
  H[3 * cols + 6] = 7.0;
  // Make path from bowl (col 5) to the notch (col 6) at row 3 pass at 7.0 m as well:
  H[3 * cols + 5] = 7.0;

  const filled = priorityFlood(H, cols, rows);

  // The centre pit at (3, 3) must fill up to the lowest spill lip = 7.0 m
  const pitIdx = 3 * cols + 3;
  assert.equal(H[pitIdx], 1.0);
  assert.equal(filled[pitIdx], 7.0, `Pit filled level should be 7.0 m, got ${filled[pitIdx]}`);

  // Test surrounding 2.0m cells in bowl: filled should also be 7.0 m
  const innerIdx = 2 * cols + 2;
  assert.equal(H[innerIdx], 2.0);
  assert.equal(filled[innerIdx], 7.0, `Inner bowl filled level should be 7.0 m, got ${filled[innerIdx]}`);

  // Test 8.0m rim cells inside: since 8.0 > spill lip (7.0), filled should remain 8.0
  const rimIdx = 1 * cols + 1;
  assert.equal(H[rimIdx], 8.0);
  assert.equal(filled[rimIdx], 8.0);

  console.log('✓ Priority-Flood 7x7 bowl depression filling passed');
}

// Test 3: Level-Pool Inflow Accumulation on 7x7 Bowl
{
  const rows = 7;
  const cols = 7;
  const H = new Float32Array(cols * rows);
  H.fill(10.0);

  // Interior bowl:
  for (let r = 1; r <= 5; r++) {
    for (let c = 1; c <= 5; c++) {
      H[r * cols + c] = 6.0;
    }
  }
  // Single centre pit cell at (3, 3): 2.0 m
  const pitIdx = 3 * cols + 3;
  H[pitIdx] = 2.0;

  // Perimeter rim is 10m, so spill level is 10.0m.
  // The bowl depression consists of the centre cell at 2.0 m with floor area A.
  // At height 6.0 m, the bowl widens to 5x5 = 25 cells.
  // Cell size: 10 m -> Area = 100 m^2 per cell.
  // Volume to fill pit from 2.0m to 6.0m = 1 cell * 4.0 m * 100 m^2 = 400 m^3.

  const cellSizeM = 10; // 100 m^2 per cell
  const runoffCoeff = 1.0;

  // Let total rainfall produce exactly 200 m^3 over the catchment draining to this pit.
  // If rainfall R is chosen such that total rain = 200 m^3, the water level will rise
  // in the 1-cell pit: 200 m^3 / 100 m^2 = 2.0 m depth (waterLevel = 4.0 m).
  // Total grid area = 49 * 100 = 4900 m^2.
  // 25 interior cells drain into pit. Rain volume generated by 25 cells = 25 * 100 * (R / 1000).
  // For 200 m^3: R = 200 / 2.5 = 80 mm.

  const depth = computeWaterDepth({
    heights: H,
    cols,
    rows,
    cellSizeM: 10,
    rainfallMm: 80,
    runoffCoeff: 1.0,
  });

  // The centre pit should receive 200 m^3 of runoff and fill to 2.0 m depth (within tolerance)
  assert.ok(Math.abs(depth[pitIdx] - 2.0) < 0.05, `Expected pit depth ~2.0 m, got ${depth[pitIdx].toFixed(3)} m`);

  // Rim cells at 6.0m should still be dry (depth = 0)
  assert.equal(depth[1 * cols + 1], 0.0);

  console.log(`✓ Level-pool volume filling passed (Pit depth: ${depth[pitIdx].toFixed(2)} m)`);
}

console.log('All pooling-core tests passed successfully!\n');
