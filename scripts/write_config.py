#!/usr/bin/env python3
"""
scripts/write_config.py
Reads API keys from .env and writes web/js/config.js (git-ignored).
Run this once after cloning to inject keys without committing them.

Usage:
  python scripts/write_config.py
"""

import os, pathlib, shutil
from dotenv import load_dotenv

ROOT = pathlib.Path(__file__).parent.parent
load_dotenv(ROOT / '.env')

GOOGLE_KEY = os.getenv('GOOGLE_MAPS_KEY', '')
if not GOOGLE_KEY:
    print('WARNING: GOOGLE_MAPS_KEY not found in .env — config.js will be empty key')

out_path = ROOT / 'web' / 'js' / 'config.js'
out_path.write_text(f'''// web/js/config.js — AUTO-GENERATED by scripts/write_config.py, git-ignored
// NEVER log or print these values.
export const GOOGLE_MAPS_KEY = "{GOOGLE_KEY}";
''')
print(f'Written: {out_path}')

# Also copy area.json into web/data/ so the server can serve it
src = ROOT / 'config' / 'area.json'
dst = ROOT / 'web' / 'data' / 'area.json'
dst.parent.mkdir(parents=True, exist_ok=True)
shutil.copy2(src, dst)
print(f'Copied:  {dst}')
