#!/usr/bin/env python3
"""
scripts/make_config.py
Reads .env and writes web/js/config.js as:
  export const GOOGLE_MAPS_KEY = "...";
Never prints the key.
"""

import os
import pathlib
import sys
from dotenv import load_dotenv

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIG_JS = ROOT / "web" / "js" / "config.js"
CONFIG_JS.parent.mkdir(parents=True, exist_ok=True)

load_dotenv(ROOT / ".env")
google_key = os.getenv("GOOGLE_MAPS_KEY", "").strip()

if not google_key:
    # Look for alternate names if any
    google_key = os.getenv("GOOGLE_KEY", "").strip()

# Write without printing the key
content = f'// web/js/config.js — auto-generated by scripts/make_config.py, git-ignored\nexport const GOOGLE_MAPS_KEY = "{google_key}";\n'

with open(CONFIG_JS, "w", encoding="utf-8") as f:
    f.write(content)

print(f"Generated {CONFIG_JS.relative_to(ROOT)}")
