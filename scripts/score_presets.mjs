// scripts/score_presets.mjs
// Runs the (unchanged) water model for every rain preset and scores it against
// web/data/validation.json. Writes docs/scores.md.   Run: node scripts/score_presets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeWaterDepth, priorityFlood } from '../web/js/pooling-core.js';
import { burnRoads } from '../web/js/road-burn.js';
import { scorePoints, scoreZones, HIT_DEPTH_M } from '../web/js/validation-core.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const grid = rd('web/data/grid.json');
const rain = rd('web/data/rain.json');
const area = rd('config/area.json');
const points = rd('web/data/validation.json');
const zones = rd('web/data/validation_zones.json');

const H = burnRoads(grid.heights, grid, rd('web/data/roads.json'), area.roadBurnM ?? 0);
const filled = priorityFlood(H, grid.cols, grid.rows);
const rows = [];
for (const [key, p] of Object.entries(rain)) {
  const mm = Math.round(p.total_mm); // same rounding the page applies to a preset
  const depth = computeWaterDepth({
    heights: H, filled, cols: grid.cols, rows: grid.rows,
    cellSizeM: grid.cellSizeM, rainfallMm: mm, runoffCoeff: area.runoffCoeff,
  });
  const s = scorePoints(points, depth, grid);
  rows.push({ key, mm, s, z: scoreZones(depth, zones) });
}

const bySrc = {};
for (const p of points) bySrc[p.source] = (bySrc[p.source] || 0) + 1;
const f = (x, d = 0) => x.toFixed(d);
let md = `# Reality check: model vs known waterlogging spots\n\n`;
md += `Points scored: **${points.length}** inside the study box (${Object.entries(bySrc).map(([k, v]) => `${k}: ${v}`).join('; ')}).\n`;
md += `Hit = deepest model water within one cell (3 x 3 cells, 30 m) of the point is over ${HIT_DEPTH_M * 100} cm. `;
md += `Wet area = share of all grid cells with more than ${HIT_DEPTH_M * 100} cm. Runoff coefficient ${area.runoffCoeff} and road burn ${area.roadBurnM ?? 0} m (config/area.json). `;
md += `Rainfall per preset = its total, rounded to the nearest mm, applied as one uniform depth (the model has no time dimension).\n\n`;
md += `| preset | rain (mm) | hits | misses | hit rate | wet area % | avg depth error (cm) |\n|---|--:|--:|--:|--:|--:|--:|\n`;
for (const { key, mm, s } of rows) {
  md += `| ${key} | ${mm} | ${s.hits} | ${s.misses} | ${f(s.hitRate)}% | ${f(s.wetPct, 1)}% | ${s.depthErrCm == null ? 'n/a' : f(s.depthErrCm)} |\n`;
}
md += `\n## Against the GCC flood-zone map\n\nZone polygons (Very High to Very Low) rasterised to the same 30 m grid; where zones overlap the most severe wins. A good model floods most Very High/High cells and few Very Low cells.\n\n| preset | Very High/High cells flooded | Very Low cells flooded | wet cells that are in Very High/High |\n|---|--:|--:|--:|\n`;
for (const { key, z } of rows) md += `| ${key} | ${f(z.highCaught)}% | ${f(z.lowFlooded)}% | ${f(z.wetInHigh)}% |\n`;
md += `\nDepth error is the mean absolute difference between the model's deepest water within one cell and the reported depth, over the ${rows[0].s.depthN} points that have a reported depth.\n`;
md += `\nGenerated by \`node scripts/score_presets.mjs\`. This is a visualisation score, not an engineering validation.\n`;
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'scores.md'), md);
console.log(md);
